## 赛制与时间

- 四赛道：A《我的世界》模组、B《我的世界》地图、C《铁锈战争》模组、D《铁锈战争》地图。
- 每队 **3–5 人**，设队长 1 名；每人只能加入 1 支队伍。
- **全程线上进行，不设路演环节。** 开发计时 **72 小时**，连续计时不补时。
- 主题分两步发布：赛前公布方向性主题词供构思，**开幕公布正式题目与特别要求**。
- 报名、组队、提交、评审、结果公示均在本平台完成，无需到场。

## 原创性边界（最重要）

### 可以做

- 搭建开发环境：IDE、构建工具、映射工具
- 学习 API、做与主题无关的技术验证
- 组队、分工、准备工具链与素材授权
- 搭建空脚手架工程（不含任何玩法内容）

### 不可以做

- 提前实现与主题相关的机制、关卡、建筑、剧情、命令或脚本
- 复用往届作品、他人作品或网络下载的完整工程
- 提前录制演示视频、提前准备用于评审的讲解材料

主办方可要求提供 **仓库提交历史**（首次提交须晚于开幕时刻）、**文件创建与修改时间**、或 **中期检查快照** 作为证据；拒绝提供视为放弃申辩。

## 作品与环境

- 必须能在主办方锁定的版本环境下加载并完整运行，锁定值于赛前 14 天公示，公布后不再变更。
- MC 模组须注明游戏版本、加载器及版本、前置模组；RW 模组须注明游戏版本、依赖与联机兼容性。
- 允许使用开源库与公开素材，但须逐项注明 **来源与许可证**；禁止打包盗版游戏文件或未授权付费资源。
- 使用 AI 生成素材须注明工具与用途，不得冒充手绘或原创美术。
- **没有现场演示**：评委完全依据作品包与演示视频判断，作品必须在干净环境下能独立跑起来。

## 提交材料

- 作品信息、团队与分工、项目说明（创意、玩法、技术、亮点）
- 可运行作品包（**直接上传到本平台**，≤200 MB；上传后自动计算 SHA-256 并查询病毒扫描。截止前仅本队可见，截止后由队长发布到评审区）
- 演示视频 **3–5 分钟**，必须包含从安装到实际游玩的完整流程，并配旁白说明玩法；这是评委了解作品的唯一动态材料
- 源码或仓库链接、第三方依赖与许可证清单、测试说明与已知问题
- 原创性佐证材料（抽查时提交）

截止前可重复提交，**以最后一次成功提交为准**；每次提交都会生成不可变版本快照，记录提交时间与哈希。

## 兼容性测试与修复

- 主办方在干净环境逐个远程加载，检查能否加载、依赖是否齐全、是否含恶意内容、**演示视频与实际运行是否一致**。
- 未通过者获得 **1 次** 修复机会，窗口为通知后 **2 小时**。
- 修复仅限可加载性问题（补依赖、修版本号、修路径与打包结构、修配置语法），**不得变更功能与内容**。
- 发现实质性新增或修改，按二次提交处理，取消评奖资格。

## 评审与奖项

- 维度与权重：可运行性与完成度 **30%**、创意与主题契合度 **25%**、玩法设计 **20%**、技术实现 **15%**、表现力与平衡性 **10%**。
- 由于全程线上、不设路演，不设路演表达评分项；团队分工体现在提交材料中，供评委参考。
- 3 名评委取平均；5 名及以上去掉一个最高分与一个最低分后取平均。
- **总分低于 60 分不授予等级奖**，对应奖项空缺。
- 赛道满 6 支队伍独立设奖；4–5 支与同游戏另一赛道合并；不足 4 支只评单项奖。
- 同一作品最多获得 2 个奖项；人气奖实名投票、单账号一票，刷票取消资格。
- 结果公示 24 小时，接受申诉。

## 知识产权

- 著作权归创作团队所有，团队须声明署名顺序与贡献比例。
- 团队授予主办方 **非独占、不可转让、免费** 的使用许可，用于宣传、展示、归档与赛后报道，期限 2 年，不含商业开发与转授权。
- 可提前 7 天书面申请撤回对外展示。
- 侵权责任由团队承担，主办方有权撤销奖项并追回。

## 违规处理

以下情形 **直接取消参赛与评奖资格**：抄袭盗用、旧作改名、代做或购买成品、伪造原创证据、包含恶意代码或外挂、攻击活动网络、重复参赛、违反法律法规。

处理程序：书面告知事实与依据 → 队伍 24 小时内申辩 → 评审组集体裁定 → 结论书面通知。对结论不服可申诉一次。

